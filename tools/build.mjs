// Assembles src/ into a playable build.
//   dist/          multi-file web build (index.html + assets/) for GitHub Pages and the desktop app
//   dist-single/   one self-contained index.html, handy for quick sharing
//
// Options (flags or environment variables):
//   --prod  / ASHFALL_PROD=1     minify game code and CSS with esbuild, leave out the dev error overlay
//   ASHFALL_OUT=name             output folder (default dist); the single-file build goes to name-single/
//   ASHFALL_TEST=1               inject tools/test-hook.js (window.__G) for automated tests
//   ASHFALL_VERSION=x.y.z        override the version stamp (default: package.json "version")
//
// Every build prepends `const GAME_VERSION="x.y.z";` inside the game scope, so any src file can show it.
//
// three.js comes from npm (package "three", WebGPU build). The game files are still concatenated into one shared
// scope, wrapped in an async function inside a generated ES module entry:
//   import * as THREE from 'three/webgpu';  import * as TSL from 'three/tsl';
//   (async function(){ 'use strict'; const GAME_VERSION=...; <src files in manifest order> })();
// esbuild bundles that entry (tree-shaking three) into dist/assets/game.js and inlines it in dist-single/index.html.
// Being async lets src/engine/02-renderer.js `await renderer.init()` (WebGPU, or its WebGL 2 fallback) at top level.
import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync, cpSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = p => join(root, 'src', p);
const read = p => readFileSync(p, 'utf8');

export function gameVersion() {
  const v = process.env.ASHFALL_VERSION || JSON.parse(read(join(root, 'package.json'))).version || '0.0.0';
  return String(v).replace(/^v/, '').replace(/[^\w.+-]/g, '');
}

export function assemble({ prod = false } = {}) {
  const { files } = JSON.parse(read(src('manifest.json')));
  const parts = files.map(f => {
    if (!existsSync(src(f))) throw new Error(`manifest lists missing file: src/${f}`);
    return `// ---- src/${f}\n${read(src(f))}`;
  });
  if (process.env.ASHFALL_TEST) parts.splice(parts.length - 1, 0, `// ---- tools/test-hook.js (test builds only)\n${read(join(root, 'tools', 'test-hook.js'))}`);
  const version = gameVersion();
  const stamp = `// ---- build stamp (tools/build.mjs)\nconst GAME_VERSION=${JSON.stringify(version)};`;
  const body = `(async function(){\n'use strict';\n${stamp}\n${parts.join('\n')}\n})();\n`;
  const game = `// generated by tools/build.mjs: three.js (WebGPU build with WebGL 2 fallback) + the concatenated game scope\nimport * as THREE from 'three/webgpu';\nimport * as TSL from 'three/tsl';\n${body}`;
  const css = files.length && existsSync(src('styles')) ? cssBundle() : '';
  const overlay = prod ? '' : read(join(root, 'tools', 'error-overlay.js'));
  return { game, css, overlay, version, html: read(src('index.template.html')) };
}

function cssBundle() {
  const order = JSON.parse(read(src('styles/order.json')));
  return order.map(f => `/* ---- src/styles/${f} */\n${read(src('styles/' + f))}`).join('\n');
}

async function loadEsbuild() {
  try { return await import('esbuild'); }
  catch { throw new Error('the build needs esbuild and three: run `npm install` first'); }
}

async function minify(code, loader) {
  const esbuild = await loadEsbuild();
  const r = await esbuild.transform(code, { loader, minify: true, target: loader === 'js' ? 'es2022' : undefined, legalComments: 'none', charset: 'utf8' });
  return r.code;
}

// Bundles the generated entry module (game scope + `import ... from 'three/webgpu'`) into one ES module.
// three.js keeps its MIT license comment (legalComments: 'eof').
async function bundle(entry, prod) {
  const esbuild = await loadEsbuild();
  const r = await esbuild.build({
    stdin: { contents: entry, resolveDir: root, sourcefile: 'ashfall-entry.js', loader: 'js' },
    bundle: true, format: 'esm', platform: 'browser', target: 'es2022', write: false, minify: prod,
    legalComments: 'eof', charset: 'utf8', logLevel: 'silent',
    define: { 'process.env.NODE_ENV': prod ? '"production"' : '"development"' },
  });
  // safe to inline in <script>: never let the code close the tag early
  return r.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
}

// The icon generated by tools/make-icons.mjs (desktop/build/icon.png) doubles as the web favicon.
function faviconPng() {
  const p = join(root, 'desktop', 'build', 'icon-64.png');
  return existsSync(p) ? readFileSync(p) : null;
}

function headExtras(html, iconHref, version) {
  let extra = `<meta name="ashfall-version" content="${version}">`;
  if (iconHref && !/rel=["']?icon/.test(html)) extra += `\n<link rel="icon" type="image/png" href="${iconHref}">`;
  return html.replace('</head>', () => extra + '\n</head>');
}

export async function build({ quiet, prod } = {}) {
  prod = prod ?? (process.argv.includes('--prod') || !!process.env.ASHFALL_PROD);
  let { game, css, overlay, html, version } = assemble({ prod });
  game = await bundle(game, prod);
  if (prod) css = await minify(css, 'css');
  const outName = process.env.ASHFALL_OUT || 'dist';
  const out = join(root, outName), single = join(root, outName + '-single');
  rmSync(out, { recursive: true, force: true }); rmSync(single, { recursive: true, force: true });
  mkdirSync(join(out, 'assets'), { recursive: true }); mkdirSync(single, { recursive: true });
  writeFileSync(join(out, 'assets', 'game.js'), game);
  writeFileSync(join(out, 'assets', 'game.css'), css);
  // PeerJS (co-op) is fetched from unpkg at runtime on the web; the desktop app serves this local copy instead.
  if (existsSync(join(root, 'vendor', 'peerjs.min.js'))) cpSync(join(root, 'vendor', 'peerjs.min.js'), join(out, 'assets', 'peerjs.min.js'));
  if (overlay) writeFileSync(join(out, 'assets', 'error-overlay.js'), overlay);
  const icon = faviconPng();
  if (icon) writeFileSync(join(out, 'assets', 'icon.png'), icon);
  if (existsSync(join(root, 'public'))) cpSync(join(root, 'public'), out, { recursive: true });
  const overlayTag = overlay ? '<script src="assets/error-overlay.js"></script>\n' : '';
  writeFileSync(join(out, 'index.html'), headExtras(html, icon && 'assets/icon.png', version)
    .replace('<!--STYLES-->', '<link rel="stylesheet" href="assets/game.css">')
    .replace('<!--SCRIPTS-->', `${overlayTag}<script type="module" src="assets/game.js"></script>`));
  writeFileSync(join(out, '.nojekyll'), '');
  writeFileSync(join(out, 'version.json'), JSON.stringify({ version, prod, test: !!process.env.ASHFALL_TEST, built: new Date().toISOString() }) + '\n');
  const overlayInline = overlay ? `<script>\n${overlay}</script>\n` : '';
  writeFileSync(join(single, 'index.html'), headExtras(html, icon && `data:image/png;base64,${icon.toString('base64')}`, version)
    .replace('<!--STYLES-->', () => `<style>\n${css}</style>`)
    .replace('<!--SCRIPTS-->', () => `${overlayInline}<script type="module">\n${game}</script>`));
  if (!quiet) console.log(`built ${outName}/ and ${outName}-single/ v${version}${prod ? ' (production, minified)' : ''}${process.env.ASHFALL_TEST ? ' (test hook)' : ''} (${(game.length / 1024).toFixed(0)} KB game code)`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  build().catch(e => { console.error('build failed:', e.message); process.exit(1); });
}
